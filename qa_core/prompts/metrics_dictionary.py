METRICS_DICTIONARY_RULES += """
中文与回答排版要求：
- 全文以简体中文为主。英文缩写首次出现需附中文解释，如 GMV（商品交易总额）、NULL（空值）、SQL（结构化查询语言）。保留字段、表名、文件名、公式及代码的原始拼写，并在正文解释其业务含义；不能猜测不明缩写。
- 先用一句中文概括答案，再按 Markdown 二级标题输出“## 已确认”“## 需确认”“## 建议”。
- 已确认：只列资料支持的事实，使用简短项目符号，按定义、公式、分子分母、统计规则、适用版本等相关项目分条，并引用来源编号 [1]。
- 需确认：说明缺失资料、适用边界、口径冲突或演示资料限制；不要把注意事项错误标记为已核验事实。没有相关缺失时可以省略本节。
- 建议：提供与当前问题相关的核对或补充资料建议，不作业务承诺。不要为填满三栏编造内容。
- 不输出 HTML，不伪造置信度、检索耗时或追踪结果。
"""


def format_direct_answer(answer: str, *, has_sources: bool) -> str:
    """为不调用模型的标准答案添加中文术语说明及忠实的展示分区。"""
    import re
    glossary = {'GMV': '商品交易总额', 'NULL': '空值', 'Asia/Shanghai': '中国标准时间',
                'user_id': '用户标识', 'pay_amount': '支付金额', 'order_status': '订单状态',
                'SQL': '结构化查询语言'}
    for term, meaning in glossary.items():
        answer = re.sub(r'(?<![A-Za-z0-9_])' + re.escape(term) + r'(?![A-Za-z0-9_]|[（(])',
                        lambda m: m.group(0) + '（' + meaning + '）', answer)
    if not has_sources or any(x in answer for x in ['信息不足', '无法确认', '口径冲突']):
        return '## 需确认\n' + answer
    if '## 已确认' in answer:
        return answer
    lines = [part.strip() for part in re.split('[；;\n]+', answer) if part.strip()]
    result = '以下为检索资料中的口径说明。\n\n## 已确认\n' + '\n'.join('- ' + line for line in lines)
    if '演示' in answer:
        result += '\n\n## 需确认\n- 上述内容属于演示资料，是否适用于实际业务需由责任部门确认。'
    return result + '\n\n## 建议\n- 使用前核对引用来源、业务日期与适用口径版本。'
